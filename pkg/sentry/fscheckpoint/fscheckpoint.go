// Package fscheckpoint defines the format of a gVisor filesystem checkpoint.
//
// Filesystem checkpoints can only be taken in sandboxes with runsc flag
// `-overlay2` enabled, which causes sandboxed filesystems to be overlaid with
// a tmpfs "upper layer" that captures filesystem changes. Each filesystem
// checkpoint contains the state of all upper layers in the sandbox.
//
// A filesystem checkpoint comprises four files:
//
//   - A "pages metadata" file and a "pages" file are generated by
//     pgalloc.MemoryFile save/restore. These contain the state of MemoryFiles
//     that store the contents of files in checkpointed tmpfs filesystems.
//
//   - A "multi-tar" file contains tar archives representing the filesystem
//     structure of checkpointed tmpfs filesystems. For regular files, these
//     tar archives store the MemoryFile offsets containing file data, avoiding
//     duplication of MemoryFile content and ensuring a dense representation of
//     possibly-sparse files.
//
//   - A "manifest" file contains information about each MemoryFile and tmpfs
//     filesystem required to load state from other checkpoint files. See type
//     definitions below.
//
// TODO: NOLINT - The tar file format involves a lot of padding to 512-byte
// boundaries. Consider gzip/zstd compression of (each archive in) the
// multi-tar file, as well as something simpler like run-length encoding of
// zero bytes.
package fscheckpoint

import (
	"fmt"
	"path"
	"strings"
	"unicode"

	"gvisor.dev/gvisor/pkg/sentry/checkpoint"
	fspb "gvisor.dev/gvisor/pkg/sentry/fscheckpoint/fscheckpoint_proto_go_proto"
)

// AllTmpfsPath is a sentinel value for the Path option of a filesystem
// checkpoint save (kernel.FSSaveOpts.Path) indicating that all tmpfs
// filesystems with a ResourceID should be checkpointed, rather than only the
// tmpfs filesystems mounted at a specific path.
const AllTmpfsPath = "all-tmpfs"

// Bundle contains groups of one or more target ResourceIDs that are saved into
// a single set of filesystem checkpoint files sharing the same prefix.
type Bundle struct {
	// Prefix is the file prefix for the checkpoint bundle (e.g., "fs" produces
	// "fs_fscheckpoint.pb", etc.; empty string in fscheckpoint only produces
	// unprefixed "fscheckpoint.pb", etc.).
	Prefix string `json:"prefix"`

	// Paths is the list of target paths in this bundle.
	Paths []checkpoint.ResourceID `json:"paths"`
}

// ParseBundles parses the list of [<prefix_name>=][<container_name>:]<path>
// checkpoint target paths, validates that no targets overlap, and groups
// them by their prefix (empty string when no prefix is specified).
func ParseBundles(vals []string) ([]Bundle, error) {
	var allPaths []checkpoint.ResourceID
	var bundles []Bundle
	prefixIdx := make(map[string]int)
	for _, val := range vals {
		part := strings.TrimSpace(val)
		if part == "" {
			continue
		}
		if strings.Contains(part, ",") {
			return nil, fmt.Errorf("path %q must not contain commas; specify multiple values instead", val)
		}
		var prefix string
		rest := part
		if pfx, r, hasPrefix := strings.Cut(part, "="); hasPrefix {
			prefix = strings.TrimSpace(pfx)
			rest = strings.TrimSpace(r)
			cleanPfx := strings.TrimSuffix(prefix, "/")
			if cleanPfx == "" || strings.ContainsAny(cleanPfx, "/:=") || cleanPfx == "." || cleanPfx == ".." || strings.IndexFunc(cleanPfx, func(r rune) bool { return unicode.IsSpace(r) || unicode.IsControl(r) }) != -1 {
				return nil, fmt.Errorf("invalid prefix %q in paths: %q", prefix, val)
			}
		}
		var c, p string
		if cPart, pPart, hasCont := strings.Cut(rest, ":"); hasCont {
			c, p = strings.TrimSpace(cPart), strings.TrimSpace(pPart)
			if c == "" {
				return nil, fmt.Errorf("empty container name in paths: %q", val)
			}
		} else {
			p = strings.TrimSpace(rest)
		}
		if p == "" || (p != AllTmpfsPath && (!path.IsAbs(p) || path.Clean(p) != p)) {
			return nil, fmt.Errorf("checkpoint path must be an absolute, clean path or %q, got: %q", AllTmpfsPath, p)
		}
		rid := checkpoint.ResourceID{ContainerName: c, Path: p}
		for _, prev := range allPaths {
			if targetsOverlap(prev, rid) {
				return nil, fmt.Errorf("overlapping targets %q and %q", prev, rid)
			}
		}
		allPaths = append(allPaths, rid)
		if idx, ok := prefixIdx[prefix]; ok {
			bundles[idx].Paths = append(bundles[idx].Paths, rid)
		} else {
			if len(bundles) > 0 {
				return nil, fmt.Errorf("multiple filesystem checkpoint bundles (%q and %q) are not supported", bundles[0].Prefix, prefix)
			}
			prefixIdx[prefix] = len(bundles)
			bundles = append(bundles, Bundle{Prefix: prefix, Paths: []checkpoint.ResourceID{rid}})
		}
	}
	return bundles, nil
}

func targetsOverlap(a, b checkpoint.ResourceID) bool {
	if a.ContainerName != "" && b.ContainerName != "" && a.ContainerName != b.ContainerName {
		return false
	}
	return a.Path == b.Path || a.Path == AllTmpfsPath || b.Path == AllTmpfsPath
}

// Manifest is the type of the JSON object stored in the manifest file.
type Manifest struct {
	// Version is the checkpoint format version.
	Version uint64 `json:"version,omitzero"`

	// RunscVersion is the version of the runsc binary that produced this
	// checkpoint.
	RunscVersion string `json:"runsc_version,omitzero"`

	// PageSize is hostarch.PageSize for the sandbox that produced this
	// checkpoint.
	//
	// TODO: NOLINT - Currently this must match during restore. Technically,
	// it's already permissible for PageSize to shrink (as long as both old and
	// new sizes remain powers of 2). Allowing PageSize to increase may require
	// being able to relocate pgalloc.MemoryFile pages during restore based on
	// information provided by tmpfs.
	PageSize uint64 `json:"page_size"`

	// Endian is hostarch.EndianString() for the sandbox that produced this
	// checkpoint.
	//
	// TODO: NOLINT - Currently this must match during restore. Removing this
	// requirement requires fixing an endianness for
	// tmpfs.fsckptRegularFileSegment.
	Endian string `json:"endian"`

	// MemoryFiles contains information about pgalloc.MemoryFiles stored in the
	// checkpoint, in order of increasing file offsets in the pages metadata
	// and pages files.
	MemoryFiles []MemoryFile `json:"memory_files"`

	// Information about filesystems stored in the checkpoint, in order of
	// increasing file offsets in the multi-tar file.
	Tmpfs []Tmpfs `json:"tmpfs"`
}

// MemoryFile represents a pgalloc.MemoryFile stored in a filesystem
// checkpoint.
type MemoryFile struct {
	// ResourceID is the value of pgalloc.MemoryFile.ResourceID().
	ResourceID checkpoint.ResourceID `json:"resource_id"`

	// PagesMetadataStart and PagesMetadataEnd are the offsets in the pages
	// metadata file at which the pages metadata for this MemoryFile begin and
	// end respectively.
	PagesMetadataStart uint64 `json:"pages_metadata_start"`
	PagesMetadataEnd   uint64 `json:"pages_metadata_end"`

	// PagesStart is the offset in the pages file at which the pages for this
	// MemoryFile begin.
	PagesStart uint64 `json:"pages_start"`
}

// Tmpfs represents a tmpfs filesystem stored in a filesystem checkpoint.
type Tmpfs struct {
	// ResourceID is the value of tmpfs.filesystem.mf.ResourceID().
	//
	// TODO: NOLINT - Assign ResourceIDs to tmpfs filesystems directly so that
	// we can also checkpoint filesystems using the main MemoryFile.
	ResourceID checkpoint.ResourceID `json:"resource_id"`

	// TarStart and TarEnd are the offsets in the multi-tar file at which the
	// tar archive for this filesystem begin and end respectively.
	TarStart uint64 `json:"tar_start"`
	TarEnd   uint64 `json:"tar_end"`
}

// FromProto converts a proto Manifest to a Manifest struct.
func FromProto(pb *fspb.Manifest) Manifest {
	m := Manifest{
		Version:      pb.Version,
		RunscVersion: pb.RunscVersion,
		PageSize:     pb.PageSize,
		Endian:       pb.Endian,
	}
	if len(pb.MemoryFiles) > 0 {
		m.MemoryFiles = make([]MemoryFile, len(pb.MemoryFiles))
		for i, mf := range pb.MemoryFiles {
			m.MemoryFiles[i] = MemoryFile{
				ResourceID:         fromProtoResourceID(mf.ResourceId),
				PagesMetadataStart: mf.PagesMetadataStart,
				PagesMetadataEnd:   mf.PagesMetadataEnd,
				PagesStart:         mf.PagesStart,
			}
		}
	}
	if len(pb.Tmpfs) > 0 {
		m.Tmpfs = make([]Tmpfs, len(pb.Tmpfs))
		for i, t := range pb.Tmpfs {
			m.Tmpfs[i] = Tmpfs{
				ResourceID: fromProtoResourceID(t.ResourceId),
				TarStart:   t.TarStart,
				TarEnd:     t.TarEnd,
			}
		}
	}
	return m
}

func fromProtoResourceID(pb *fspb.ResourceID) checkpoint.ResourceID {
	if pb == nil {
		return checkpoint.ResourceID{}
	}
	return checkpoint.ResourceID{
		ContainerName: pb.ContainerName,
		Path:          pb.Path,
	}
}
