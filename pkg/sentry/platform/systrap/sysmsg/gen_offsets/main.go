// Command gen_offsets writes the Go offsets of the systrap stub's exported symbols.
package main

import (
	"debug/elf"
	"fmt"
	"log"
	"os"
	"slices"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gen_offsets <stub ELF> <output Go file>")
	}
	stub, err := elf.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer stub.Close()
	symbols, err := stub.Symbols()
	if err != nil {
		log.Fatal(err)
	}
	slices.SortFunc(symbols, func(a, b elf.Symbol) int { return strings.Compare(a.Name, b.Name) })
	var out strings.Builder
	out.WriteString("// Code generated by gen_offsets; DO NOT EDIT.\n\npackage sysmsg\n\n")
	for _, sym := range symbols {
		// pie.lds.S links the stub at address zero, so symbol values are
		// offsets into the blob embedded in the Sentry.
		if sym.Section != elf.SHN_UNDEF && strings.HasPrefix(sym.Name, "__export_") {
			fmt.Fprintf(&out, "var Sighandler_blob_offset__%s = 0x%016x\n", strings.ReplaceAll(sym.Name, ".", "_"), sym.Value)
		}
	}
	if err := os.WriteFile(os.Args[2], []byte(out.String()), 0644); err != nil {
		log.Fatal(err)
	}
}
