// This utility generates a Go source file that has the syscall
// numbers and names from the `zsysnum_linux_<arch>.go` files of
// `golang.org/x/sys/unix`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

var (
	pkg = flag.String("package", "", "package name of the Go source file to write")
	out = flag.String("out", "", "path of the Go source file to write")
)

func main() {
	flag.Parse()
	files := make(map[string]string)
	for _, path := range flag.Args() {
		arch, ok := strings.CutPrefix(strings.TrimSuffix(filepath.Base(path), ".go"), "zsysnum_linux_")
		if !ok {
			fmt.Fprintf(os.Stderr, "%q is not a zsysnum_linux_<arch>.go file\n", path)
			os.Exit(1)
		}
		files[arch] = path
	}
	source, err := generate(*pkg, files)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot generate Linux syscalls: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, source, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "cannot write %q: %v\n", *out, err)
		os.Exit(1)
	}
}

// syscall is one Linux syscall.
type syscall struct {
	number uint64
	name   string
}

// generate returns the Go source file for the given package.
func generate(pkg string, files map[string]string) ([]byte, error) {
	archs := make([]string, 0, len(files))
	for arch := range files {
		archs = append(archs, arch)
	}
	sort.Strings(archs)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by //pkg/sentry/syscalls/linux/genlinuxsyscalls. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n", pkg)
	for _, arch := range archs {
		syscalls, err := parse(files[arch])
		if err != nil {
			return nil, fmt.Errorf("%s: %w", arch, err)
		}
		if len(syscalls) == 0 {
			return nil, fmt.Errorf("%s: no syscalls in %q", arch, files[arch])
		}
		fmt.Fprintf(&b, "\n// linuxSyscalls%s maps the numbers of the Linux syscalls on %s to their names.\n", strings.ToUpper(arch), arch)
		fmt.Fprintf(&b, "var linuxSyscalls%s = map[uintptr]string{\n", strings.ToUpper(arch))
		for _, sc := range syscalls {
			fmt.Fprintf(&b, "\t%d: %q,\n", sc.number, sc.name)
		}
		fmt.Fprintf(&b, "}\n")
	}
	return format.Source(b.Bytes())
}

// parse returns the syscalls of the `SYS_*` constants in file `path`.
func parse(path string) ([]syscall, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, err
	}
	var syscalls []syscall
	numbers := make(map[uint64]string)
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			value := spec.(*ast.ValueSpec)
			if len(value.Names) != 1 || len(value.Values) != 1 {
				continue
			}
			name, ok := strings.CutPrefix(value.Names[0].Name, "SYS_")
			if !ok {
				continue
			}
			lit, ok := value.Values[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.INT {
				return nil, fmt.Errorf("SYS_%s is not an integer", name)
			}
			number, err := strconv.ParseUint(lit.Value, 0, 64)
			if err != nil {
				return nil, fmt.Errorf("SYS_%s: %w", name, err)
			}
			if other, ok := numbers[number]; ok {
				return nil, fmt.Errorf("SYS_%s and SYS_%s have the same number %d", other, name, number)
			}
			numbers[number] = name
			syscalls = append(syscalls, syscall{number: number, name: strings.ToLower(name)})
		}
	}
	sort.Slice(syscalls, func(i, j int) bool { return syscalls[i].number < syscalls[j].number })
	return syscalls, nil
}
