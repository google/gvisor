func TestProcessDocuments_SnapshotRestore(t *testing.T) {
	ctx := context.Background()

	snapDir := t.TempDir()
	outDir := t.TempDir()

	// 1. Create a pre-warmed snapshot containing /opt/templates/header.txt
	if err := WarmSnapshot(ctx, snapDir); err != nil {
		t.Fatalf("WarmSnapshot failed: %v", err)
	}

	// 2. Run ProcessDocuments restoring from that snapshot
	cfg := ProcessConfig{
		OutputDir:   outDir,
		SnapshotDir: snapDir,
		Command:     "cat /opt/templates/header.txt > /output/header_restored.txt",
		Timeout:     15 * time.Second,
		Network:     "none",
	}

	if err := ProcessDocuments(ctx, cfg); err != nil {
		t.Fatalf("ProcessDocuments with snapshot restore failed: %v", err)
	}

	// 3. Verify restored file
	restoredFile := filepath.Join(outDir, "header_restored.txt")
	gotBytes, err := os.ReadFile(restoredFile)
	if err != nil {
		t.Fatalf("failed to read restored header file: %v", err)
	}

	if !strings.Contains(string(gotBytes), "Generated by gVisor Snapshot") {
		t.Errorf("restored content mismatch, got: %q", string(gotBytes))
	}
}

func TestProcessDocuments_ReadOnlyEnforcement(t *testing.T) {
	ctx := context.Background()

	inDir := t.TempDir()
	outDir := t.TempDir()

	cfg := ProcessConfig{
		InputDir:  inDir,
		OutputDir: outDir,
		Command:   "touch /input/tamper.txt",
		Timeout:   10 * time.Second,
		Network:   "none",
	}

	err := ProcessDocuments(ctx, cfg)
	if err == nil {
		t.Fatal("expected writing to read-only /input to fail, but it succeeded")
	}

	tamperFile := filepath.Join(inDir, "tamper.txt")
	if _, statErr := os.Stat(tamperFile); !os.IsNotExist(statErr) {
		t.Errorf("tamper file was created on host input directory")
	}
}

func TestProcessDocuments_WorkingDir(t *testing.T) {
	ctx := context.Background()

	inDir := t.TempDir()
	outDir := t.TempDir()

	cfg := ProcessConfig{
		InputDir:   inDir,
		OutputDir:  outDir,
		WorkingDir: "/input",
		Command:    "pwd > /output/cwd.txt",
		Timeout:    10 * time.Second,
		Network:    "none",
	}

	if err := ProcessDocuments(ctx, cfg); err != nil {
		t.Fatalf("ProcessDocuments failed: %v", err)
	}

	cwdFile := filepath.Join(outDir, "cwd.txt")
	gotBytes, err := os.ReadFile(cwdFile)
	if err != nil {
		t.Fatalf("failed to read cwd output file: %v", err)
	}

	got := strings.TrimSpace(string(gotBytes))
	want := "/input"
	if got != want {
		t.Errorf("working directory = %q, want %q", got, want)
	}
}

