func TestProcessDocuments_BasicTransform(t *testing.T) {
	ctx := context.Background()

	inDir := t.TempDir()
	outDir := t.TempDir()

	// Create test input files.
	inputFile := filepath.Join(inDir, "sample.txt")
	if err := os.WriteFile(inputFile, []byte("hello from untrusted input\n"), 0644); err != nil {
		t.Fatalf("failed to write input file: %v", err)
	}

	cfg := ProcessConfig{
		InputDir:  inDir,
		OutputDir: outDir,
		Timeout:   15 * time.Second,
		Network:   "none",
	}

	if err := ProcessDocuments(ctx, cfg); err != nil {
		t.Fatalf("ProcessDocuments failed: %v", err)
	}

	// Verify output file was created with uppercase content.
	outputFile := filepath.Join(outDir, "sample.txt")
	gotBytes, err := os.ReadFile(outputFile)
	if err != nil {
		t.Fatalf("failed to read output file: %v", err)
	}

	got := string(gotBytes)
	want := "HELLO FROM UNTRUSTED INPUT\n"
	if got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

func TestProcessDocuments_TimeoutEnforcement(t *testing.T) {
	ctx := context.Background()

	cfg := ProcessConfig{
		Command: "sleep 30",
		Timeout: 2 * time.Second,
		Network: "none",
	}

	start := time.Now()
	err := ProcessDocuments(ctx, cfg)
	elapsed := time.Since(start)

	if err == nil {
		t.Fatal("expected execution to fail with timeout, but it succeeded")
	}

	if !strings.Contains(err.Error(), "timed out") && !strings.Contains(err.Error(), "deadline exceeded") && !strings.Contains(err.Error(), "signal: killed") {
		t.Errorf("expected timeout error message, got: %v", err)
	}

	if elapsed > 10*time.Second {
		t.Errorf("execution took too long to abort (%v), expected ~2s", elapsed)
	}
}

